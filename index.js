/** Clamp a numeric option into [min, max], falling back when it is not a number. */
function clampNumber(value, min, max, fallback) {
  if (!Number.isFinite(value)) return fallback;
  return Math.min(max, Math.max(min, Math.round(value)));
}

/** Compose a piece: step grids per track, plus the score text for that piece. */
function composePiece(input) {
  const composition = composeMusic({
    style: input.style,
    key: input.key,
    scale: input.scale,
    bars: clampNumber(input.bars, 1, MAX_BARS, 4),
    stepsPerBar: clampNumber(input.stepsPerBar, 4, 16, 8),
    rangeBase: clampNumber(input.rangeBase, 1, 6, 3),
    seed: input.seed,
    energy: input.energy,
    texture: input.texture,
    register: input.register,
    drums: input.drums,
    instruments: input.instruments,
  });
  const stepBeats = 4 / composition.stepsPerBar;
  const tempo = Number.isFinite(input.tempo) && input.tempo > 0 ? Math.round(input.tempo) : DEFAULT_TEMPO;
  const tracks = composition.tracks.map((track) => ({
    name: track.name,
    instrument: track.instrument,
    steps: track.steps,
    // Percussion keeps one note per hit; pitched tracks merge held steps.
    notes: track.notes ?? stepsToNotes(track.steps, stepBeats),
  }));
  const text = formatScoreText({ tempo, title: input.title ?? '', tracks });
  return { ...composition, stepBeats, tempo, tracks, text, score: stepsToScore(composition.steps, stepBeats) };
}

/**
 * Resolve the composition options from a prompt and explicit overrides.
 *
 * The prompt is read first; an explicit argument (style, key, scale, tempo,
 * bars, instruments, drums) always wins over what the prompt said.
 */
function resolveComposition(options, input) {
  const source = input ?? {};
  const prompt = typeof source.prompt === 'string' ? source.prompt.trim() : '';
  const plan = prompt === ''
    ? undefined
    : parseMusicPrompt(prompt, {
      defaultTempo: options.music.defaultTempo,
      defaultStyle: source.style,
      defaultKey: source.key,
      defaultScale: source.scale,
      defaultBars: source.bars,
    });
  const one = typeof source.instrument === 'string' && source.instrument.trim() !== '' ? source.instrument.trim() : undefined;
  const planned = plan?.instruments ?? {};
  return {
    plan,
    prompt,
    style: source.style ?? plan?.style ?? 'pop',
    key: source.key ?? plan?.key ?? 'C',
    scale: source.scale ?? plan?.scale ?? 'major',
    tempo: Number.isFinite(source.tempo) && source.tempo > 0
      ? Math.round(source.tempo)
      : (plan?.tempo ?? options.music.defaultTempo),
    bars: Number.isFinite(source.bars) && source.bars > 0
      ? Math.round(source.bars)
      : (plan?.bars ?? 4),
    energy: plan?.energy,
    texture: plan?.texture,
    register: plan?.register,
    drums: source.drums === true ? true : (source.drums === false ? false : plan?.drums),
    instruments: {
      melody: one ?? source.melodyInstrument ?? planned.melody,
      harmony: one ?? source.harmonyInstrument ?? planned.harmony,
      bass: one ?? source.bassInstrument ?? planned.bass,
    },
  };
}

/** Accept a `gm:` SoundFont selection, falling back to the configured preset. */
function resolveInstrument(options, value) {
  if (typeof value === 'string') {
    const trimmed = value.trim();
    if (parseGmInstrument(trimmed) !== null) return trimmed;
  }
  return options.music.defaultInstrument;
}

/** Resolve the piece to render from tool or route input. */
function resolvePieceInput(options, input) {
  const source = input ?? {};
  const fallbackTempo = Number.isFinite(source.tempo) && source.tempo > 0
    ? Math.round(source.tempo)
    : options.music.defaultTempo;

  if (typeof source.text === 'string' && source.text.trim() !== '') {
    const parsed = parseScoreText(source.text);
    const piece = sanitizePiece({
      tempo: Number.isFinite(source.tempo) && source.tempo > 0 ? source.tempo : parsed.tempo,
      title: typeof source.title === 'string' && source.title.trim() !== '' ? source.title : parsed.title,
      tracks: parsed.tracks.map((track) => ({ ...track, instrument: resolveInstrument(options, track.instrument) })),
    });
    if (piece.tracks.length === 0) throw httpError(400, 'スコアテキストに有効なトラックがありません。');
    return piece;
  }

  if (Array.isArray(source.tracks) && source.tracks.length > 0) {
    const piece = sanitizePiece({
      tempo: fallbackTempo,
      title: source.title,
      tracks: source.tracks.map((track) => ({
        ...track,
        instrument: resolveInstrument(options, track?.instrument),
      })),
    });
    if (piece.tracks.length === 0) throw httpError(400, 'tracks に有効なノートがありません。');
    return piece;
  }

  const notes = resolveNotes(source);
  if (notes.length === 0) throw httpError(400, 'notes / score / tracks / text のいずれかを指定してください。');
  return sanitizePiece({
    tempo: fallbackTempo,
    title: source.title,
    tracks: [{
      name: 'track 1',
      instrument: resolveInstrument(options, source.instrument),
      notes: sequentialToNotes(notes),
    }],
  });
}

/** Render a piece through the SoundFont bank. */
async function renderPieceToWav(options, piece, volume) {
  if (!soundFontAvailable(options.soundfont.path)) {
    throw httpError(400, `SoundFont が見つかりません: ${options.soundfont.path || '(未設定)'}`);
  }
  const buffer = await renderSoundFontTracks(options.soundfont.path, {
    tempo: piece.tempo,
    tracks: piece.tracks,
    volume,
    gain: options.soundfont.gain,
    releaseSeconds: options.soundfont.releaseSeconds,
  });
  return encodeWav(buffer, 44100);
}

/** Synthesize one music piece from text, tracks, or a legacy note list. */
async function generateMusic(options, input) {
  const volume = typeof input?.volume === 'number' && Number.isFinite(input.volume)
    ? Math.min(1, Math.max(0, input.volume))
    : 0.7;
  const piece = resolvePieceInput(options, input);
  const lengthBeats = pieceLengthBeats(piece);
  if (lengthBeats <= 0) throw httpError(400, 'ノートがありません。');
  const noteCount = pieceNoteCount(piece);
  if (noteCount > options.music.maxNotes) throw httpError(400, `ノート数が上限 (${options.music.maxNotes}) を超えています。`);
  const totalSeconds = (lengthBeats * 60) / piece.tempo;
  if (totalSeconds > options.music.maxSeconds) throw httpError(400, `演奏時間が上限 (${options.music.maxSeconds}s) を超えています。`);

  const data = await renderPieceToWav(options, piece, volume);
  const info = readWaveInfo(data);
  const instruments = [...new Set(piece.tracks.map((track) => track.instrument))];
  return {
    data,
    mediaType: 'audio/wav',
    instrument: instruments.length === 1 ? instruments[0] : instruments.join(' + '),
    instruments,
    tempo: piece.tempo,
    noteCount,
    trackCount: piece.tracks.length,
    seconds: typeof info?.seconds === 'number' && info.seconds > 0 ? info.seconds : totalSeconds,
    text: formatScoreText(piece),
  };
}

