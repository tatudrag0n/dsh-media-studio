// #region HTTP plumbing

/** Wrap one handler, turning thrown HttpError-like values into JSON responses. */
function respond(handler) {
  return async (request) => {
    try {
      return await handler(request);
    } catch (cause) {
      const status = typeof cause?.status === 'number' ? cause.status : 500;
      const message = messageOf(cause);
      return jsonResponse({ error: { code: typeof cause?.code === 'string' ? cause.code : 'MEDIA_STUDIO_ERROR', message } }, status);
    }
  };
}

/** Construct a tagged HTTP failure. */
function httpError(status, message, code) {
  const error = new Error(message);
  error.status = status;
  error.code = code ?? 'MEDIA_STUDIO_ERROR';
  return error;
}

/** Read a small JSON object body. */
async function readJsonBody(request) {
  const text = await request.text();
  if (text.trim() === '') return {};
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw httpError(400, 'リクエスト本文が JSON ではありません。');
  }
  if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw httpError(400, 'リクエスト本文は JSON オブジェクトである必要があります。');
  }
  return parsed;
}

/** JSON response with the panel's no-store policy. */
function jsonResponse(value, status = 200) {
  return new Response(JSON.stringify(value), {
    status,
    headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' },
  });
}

/** Binary response. */
function bytesResponse(bytes, mediaType) {
  return new Response(bytes, {
    status: 200,
    headers: {
      'content-type': mediaType,
      'content-length': String(bytes.byteLength),
      'cache-control': 'no-store',
    },
  });
}

/** Fetch with a request timeout and the caller's cancellation. */
async function fetchWithTimeout(url, init, timeoutMs, signal) {
  const timeout = AbortSignal.timeout(timeoutMs);
  const combined = signal === undefined ? timeout : AbortSignal.any([signal, timeout]);
  try {
    return await fetch(url, { ...init, signal: combined });
  } catch (cause) {
    if (cause?.name === 'TimeoutError') throw httpError(504, `リクエストがタイムアウトしました（${Math.round(timeoutMs / 1000)}秒）。`);
    throw cause;
  }
}

/** The start of an upstream error body, for the failure message. */
async function errorSnippet(response) {
  try {
    const text = (await response.text()).trim().replace(/\s+/gu, ' ');
    return text === '' ? '' : truncate(text, 300);
  } catch {
    return '';
  }
}

/** Resolve one credential: literal config, then the credential store, then env. */
async function resolveCredential(ctx, apiKeyEnv, literal) {
  if (typeof literal === 'string' && literal.trim() !== '') return literal.trim();
  const credentials = ctx.get?.('credentials');
  if (credentials !== undefined) {
    try {
      const resolved = await credentials.resolve(apiKeyEnv);
      const value = typeof resolved?.value === 'string' ? resolved.value.trim() : '';
      if (value !== '') return value;
    } catch {
      // Fall through to the process environment.
    }
  }
  const fromEnv = process.env[apiKeyEnv];
  return typeof fromEnv === 'string' && fromEnv.trim() !== '' ? fromEnv.trim() : undefined;
}

