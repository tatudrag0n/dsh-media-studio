/**
 * Resolve one video through the configured provider.
 *
 * The local backend comes in two shapes. A text-to-video recipe paints straight
 * from the prompt; an image-to-video recipe needs a first frame. When a text
 * request meets an image recipe, the plugin paints the keyframe **locally**
 * with the motion renderer and animates that, so "text in, video out" never
 * needs an image provider and never leaves the machine.
 */
async function generateVideo(ctx, options, input) {
  const provider = options.video.provider;
  if (provider === 'local') {
    const recipe = resolveRecipe(input.recipe ?? options.video.recipe);
    const hasFrame = input.imagePath !== undefined || input.imageBytes !== undefined;
    if (recipe.mode === 'image' && !hasFrame) {
      const prompt = requireText(input.prompt, options.maxVideoPrompt, 'prompt');
      const keyframe = await paintLocalKeyframe(options, prompt, input);
      const result = await runVideoBackend(ctx, options, { ...input, prompt, imageBytes: keyframe.data });
      return { ...result, keyframeFromPrompt: true, keyframeSource: 'local' };
    }
  }
  if (provider !== 'frames') {
    requireText(input.prompt, options.maxVideoPrompt, 'prompt');
  }
  return await runVideoBackend(ctx, options, input);
}

/**
 * Paint the first frame of a text request, locally.
 *
 * The frame is a drawn title card: the same typography the motion renderer
 * uses, so the animated result looks designed rather than generated.
 */
async function paintLocalKeyframe(options, prompt, input) {
  const size = resolveVideoSize(input.aspect, input.width, input.height);
  const spec = parseMotionSpec({
    template: 'title',
    text: String(prompt).slice(0, 160),
    subtitle: '',
    style: 'smooth',
    width: size.width,
    height: size.height,
    fps: 12,
    duration: 4,
    seed: 1,
  });
  return await renderMotionStill(options, spec);
}

