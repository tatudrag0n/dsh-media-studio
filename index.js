/** Candidate PowerShell executables, tried in order. */
const POWERSHELL_CANDIDATES = [
  'pwsh',
  'C:\\Program Files\\PowerShell\\7\\pwsh.exe',
  'powershell.exe',
];

/** Run a PowerShell script file and return its stdout. */
async function runPowerShell(args, timeoutMs) {
  let missing;
  for (const executable of POWERSHELL_CANDIDATES) {
    if (executable.includes(sep) && !existsSync(executable)) continue;
    try {
      return await spawnCollect(executable, args, timeoutMs);
    } catch (cause) {
      if (cause?.code === 'ENOENT') {
        missing = cause;
        continue;
      }
      throw cause;
    }
  }
  throw new Error(`PowerShell が見つかりません: ${messageOf(missing)}`);
}

/** Spawn one process, collect stdout, and fail on a non-zero exit or timeout. */
function spawnCollect(executable, args, timeoutMs) {
  return new Promise((resolvePromise, rejectPromise) => {
    let settled = false;
    const child = spawn(executable, args, { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
    const stdout = [];
    const stderr = [];
    const timer = setTimeout(() => {
      if (settled) return;
      settled = true;
      child.kill();
      rejectPromise(new Error(`PowerShell が ${Math.round(timeoutMs / 1000)} 秒でタイムアウトしました。`));
    }, timeoutMs);
    child.stdout?.on('data', (chunk) => stdout.push(chunk));
    child.stderr?.on('data', (chunk) => stderr.push(chunk));
    child.on('error', (cause) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      rejectPromise(cause);
    });
    child.on('close', (code) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      const output = Buffer.concat(stdout).toString('utf8');
      if (code === 0) {
        resolvePromise(output);
        return;
      }
      const reason = Buffer.concat(stderr).toString('utf8').trim();
      rejectPromise(new Error(`PowerShell が終了コード ${code} で失敗しました。${reason === '' ? '' : ` ${truncate(reason.replace(/\s+/gu, ' '), 500)}`}`));
    });
  });
}

