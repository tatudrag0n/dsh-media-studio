/** Resolve speech audio through the configured provider. */
async function generateSpeech(ctx, options, input) {
  const text = requireText(input.text, options.maxSpeechText, 'text');
  const format = pick(input.format, ['wav', 'mp3'], options.speech.format);
  const rate = Number.isFinite(input.rate) ? normalizeRate(input.rate) : options.speech.rate;
  const requestedVoice = nonEmpty(input.voice) ?? options.speech.voice;

  if (options.speech.provider === 'openai') {
    const credential = await resolveCredential(ctx, options.speech.apiKeyEnv, options.speech.apiKey);
    if (credential === undefined) throw httpError(400, `音声合成には ${options.speech.apiKeyEnv} が必要です（speech.provider: openai）。Speech needs the ${options.speech.apiKeyEnv} credential.`);
    const voice = requestedVoice ?? 'alloy';
    const response = await fetchWithTimeout(`${options.speech.baseURL}/audio/speech`, {
      method: 'POST',
      headers: { authorization: `Bearer ${credential}`, 'content-type': 'application/json' },
      body: JSON.stringify({ model: options.speech.model, input: text, voice, response_format: format }),
    }, options.speech.timeoutMs, input.signal);
    if (!response.ok) throw httpError(502, `音声エンドポイントが HTTP ${response.status} を返しました。${await errorSnippet(response)}`);
    const bytes = new Uint8Array(await response.arrayBuffer());
    if (bytes.byteLength === 0) throw httpError(502, '音声エンドポイントが空の応答を返しました。');
    return { data: bytes, mediaType: format === 'mp3' ? 'audio/mpeg' : 'audio/wav', provider: 'openai', model: options.speech.model, voice, format };
  }

  const installed = await listSystemVoices(options);
  if (installed.voices.length === 0) {
    throw httpError(503, `Windows の音声合成を利用できません${installed.error === undefined ? '（声がインストールされていません）' : `: ${installed.error}`}。音声を追加するか、speech.provider を openai にしてください。`);
  }
  const voice = chooseVoice(installed.voices, requestedVoice, text);
  if (voice === undefined) throw httpError(503, '音声合成の声を選択できませんでした。');
  const data = await runSapiSynthesis(options, { text, voice, rate });
  const info = readWaveInfo(data);
  return { data, mediaType: 'audio/wav', provider: 'system', model: voice, voice, format: 'wav', seconds: info?.seconds };
}

/** Run the SAPI helper and return the synthesized WAV bytes. */
async function runSapiSynthesis(options, { text, voice, rate }) {
  const directory = await mkdtemp(join(tmpdir(), 'dsh-media-studio-'));
  try {
    const scriptPath = join(directory, 'synthesize.ps1');
    const optionsPath = join(directory, 'options.json');
    const outputPath = join(directory, 'speech.wav');
    await writeFile(scriptPath, sapiSynthesisScript(), 'utf8');
    await writeFile(optionsPath, JSON.stringify({ text, voice: voice ?? '', rate: normalizeRate(rate), output: outputPath }), 'utf8');
    await runPowerShell(['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', scriptPath, '-OptionsPath', optionsPath], options.speech.timeoutMs);
    const data = new Uint8Array(await readFile(outputPath));
    if (data.byteLength === 0) throw new Error('音声合成が空の WAV を生成しました。');
    return data;
  } finally {
    await rm(directory, { recursive: true, force: true }).catch(() => {});
  }
}

/** List installed SAPI voices, cached for the panel. */
async function listSystemVoices(options) {
  const now = Date.now();
  if (voiceCache.at !== 0 && now - voiceCache.at < VOICE_CACHE_MS) {
    return { voices: voiceCache.voices, error: voiceCache.error };
  }
  let voices = [];
  let error;
  const directory = await mkdtemp(join(tmpdir(), 'dsh-media-studio-voices-'));
  try {
    const scriptPath = join(directory, 'voices.ps1');
    await writeFile(scriptPath, sapiVoiceListScript(), 'utf8');
    const output = await runPowerShell(['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', scriptPath], 20000);
    voices = parseVoiceList(output);
  } catch (cause) {
    error = messageOf(cause);
  } finally {
    await rm(directory, { recursive: true, force: true }).catch(() => {});
  }
  voiceCache.at = Date.now();
  voiceCache.voices = voices;
  voiceCache.error = error;
  return { voices, error };
}

/** Parse the JSON the SAPI voice-list helper prints. */
function parseVoiceList(output) {
  const text = output.trim();
  if (text === '') return [];
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    return [];
  }
  const rows = Array.isArray(parsed) ? parsed : [parsed];
  return rows
    .filter((row) => row !== null && typeof row === 'object' && typeof row.name === 'string' && row.name !== '')
    .map((row) => ({
      name: row.name,
      culture: typeof row.culture === 'string' ? row.culture : '',
      gender: typeof row.gender === 'string' ? row.gender : '',
    }));
}

