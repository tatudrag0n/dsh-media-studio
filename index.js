/** Resolve an image through the configured provider. */
/**
 * CLIP は英語しか読めない。日本語のプロンプトはローカルモデルに届かないので、
 * 生成の前に英語の描写へ直す（llm が無ければそのまま渡す）。
 */
async function toEnglishPrompt(ctx, options, prompt) {
  if (!/[\u3040-\u30ff\u4e00-\u9fff]/u.test(prompt)) return prompt;
  const llm = ctx?.get?.("llm");
  if (llm === undefined) return prompt;
  try {
    const route = await resolveWritingRoute(ctx, { writing: options.writing ?? {} });
    const { text } = await generateText(ctx, route, {
      system: "Turn the description into one concise English text-to-image prompt: subject, setting, light, style. Reply with the prompt only, no quotes, no commentary.",
      messages: [{ role: "user", content: [{ type: "text", text: prompt }] }],
      maxTokens: 200,
      temperature: 0.2,
      timeoutMs: 30000,
    });
    const line = text.trim().split(/\r?\n/u)[0].trim();
    return line === "" ? prompt : line;
  } catch {
    return prompt;
  }
}

/** ローカルの diffusers で 1 枚描く (the local image backend). */
async function localImageGenerate(ctx, options, input) {
  let python;
  try {
    python = await resolvePython({ video: { pythonPath: options.image.pythonPath || options.video?.pythonPath } }, ['torch', 'diffusers']);
  } catch (cause) {
    throw new Error(`ローカル画像生成には torch と diffusers が必要です。\`pip install torch diffusers transformers accelerate\` を実行するか、image.provider を comfyui か openai に切り替えてください。The local image backend needs torch and diffusers (${cause instanceof Error ? cause.message : String(cause)}).`);
  }
  const directory = await mkdtemp(join(tmpdir(), 'media-studio-image-'));
  const output = join(directory, 'image.png');
  try {
    const script = fileURLToPath(new URL('./image_local.py', import.meta.url));
    await runProcess(python, [
      script,
      '--prompt', await toEnglishPrompt(ctx, options, input.prompt),
      '--negative', options.image.negativePrompt ?? '',
      '--width', String(input.width),
      '--height', String(input.height),
      '--steps', String(options.image.steps ?? 4),
      '--seed', String(input.seed ?? 0),
      '--model', nonEmpty(options.image.model) ?? DEFAULT_LOCAL_IMAGE_MODEL,
      '--out', output,
    ], { timeoutMs: options.image.timeoutMs, signal: input.signal });
    const bytes = await readFile(output);
    return { data: bytes, mediaType: 'image/png', provider: 'local', model: nonEmpty(options.image.model) ?? DEFAULT_LOCAL_IMAGE_MODEL, width: input.width, height: input.height };
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

async function generateImage(ctx, options, input) {
  const prompt = requireText(input.prompt, options.maxImagePrompt, 'prompt');
  const aspect = ASPECTS.includes(input.aspect) ? input.aspect : 'square';
  const size = resolveImageSize(aspect, input.width, input.height);
  if (options.image.provider === 'local') {
    return await localImageGenerate(ctx, options, {
      prompt,
      width: size.width,
      height: size.height,
      seed: numberOrUndefined(input.seed),
      signal: input.signal,
    });
  }
  if (options.image.provider === 'openai') {
    const credential = await resolveCredential(ctx, options.image.apiKeyEnv, options.image.apiKey);
    if (credential === undefined) throw httpError(400, `画像生成には ${options.image.apiKeyEnv} が必要です（image.provider: openai）。Image generation needs the ${options.image.apiKeyEnv} credential.`);
    const model = nonEmpty(input.model) ?? options.image.model ?? DEFAULT_OPENAI_IMAGE_MODEL;
    const body = openAiImageBody({ prompt, model, size: resolveOpenAiSize(aspect, model), seed: numberOrUndefined(input.seed) });
    const response = await fetchWithTimeout(`${options.image.baseURL}/images/generations`, {
      method: 'POST',
      headers: { authorization: `Bearer ${credential}`, 'content-type': 'application/json', accept: 'application/json' },
      body: JSON.stringify(body),
    }, options.image.timeoutMs, input.signal);
    if (!response.ok) throw httpError(502, `画像エンドポイントが HTTP ${response.status} を返しました。${await errorSnippet(response)}`);
    const payload = await response.json().catch(() => undefined);
    const decoded = decodeOpenAiImagePayload(payload);
    if (decoded === undefined) throw httpError(502, '画像エンドポイントの応答に画像がありませんでした。The image response carried no image.');
    if (decoded.url !== undefined) {
      const imageResponse = await fetchWithTimeout(decoded.url, { method: 'GET' }, options.image.timeoutMs, input.signal);
      if (!imageResponse.ok) throw httpError(502, `画像の取得が HTTP ${imageResponse.status} で失敗しました。`);
      const bytes = new Uint8Array(await imageResponse.arrayBuffer());
      return { data: bytes, mediaType: imageMediaTypeFromResponse(imageResponse.headers.get('content-type'), bytes), provider: 'openai', model, width: size.width, height: size.height };
    }
    return { data: decoded.data, mediaType: decoded.mediaType, provider: 'openai', model, width: size.width, height: size.height };
  }

  if (options.image.provider === 'comfyui') {
    const model = nonEmpty(input.model) ?? options.image.model ?? 'z-image-turbo';
    const bytes = await comfyuiGenerate(options.image.baseURL, prompt, size.width, size.height, numberOrUndefined(input.seed), options.image.timeoutMs, input.signal, options);
    return { data: bytes, mediaType: 'image/png', provider: 'comfyui', model, width: size.width, height: size.height };
  }

  const model = nonEmpty(input.model) ?? options.image.model ?? DEFAULT_POLLINATIONS_MODEL;
  const url = buildPollinationsUrl({ prompt, width: size.width, height: size.height, seed: numberOrUndefined(input.seed), model });
  const response = await fetchWithTimeout(url, { method: 'GET', headers: { accept: 'image/*' } }, options.image.timeoutMs, input.signal);
  const contentType = response.headers.get('content-type') ?? '';
  if (!response.ok || contentType.startsWith('text/')) {
    throw httpError(502, `画像生成サービスが HTTP ${response.status} を返しました。${await errorSnippet(response)}`);
  }
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.byteLength === 0) throw httpError(502, '画像生成サービスが空の応答を返しました。');
  return { data: bytes, mediaType: imageMediaTypeFromResponse(contentType, bytes), provider: 'pollinations', model, width: size.width, height: size.height };
}

