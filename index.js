/** Transcribe audio bytes through the configured provider. */
async function transcribe(ctx, options, input) {
  const language = normalizeLanguage(input.language) ?? options.transcription.language;
  if (options.transcription.provider === 'openai') {
    const credential = await resolveCredential(ctx, options.transcription.apiKeyEnv, options.transcription.apiKey);
    if (credential === undefined) throw httpError(400, `文字起こしには ${options.transcription.apiKeyEnv} が必要です（transcription.provider: openai）。Transcription needs the ${options.transcription.apiKeyEnv} credential.`);
    const form = new FormData();
    const mime = typeof input.mime === 'string' && input.mime !== '' ? input.mime : 'audio/wav';
    form.append('file', new Blob([input.audio], { type: mime }), `audio.${extensionForMime(mime)}`);
    form.append('model', options.transcription.model);
    if (language !== undefined) form.append('language', language);
    const response = await fetchWithTimeout(`${options.transcription.baseURL}/audio/transcriptions`, {
      method: 'POST',
      headers: { authorization: `Bearer ${credential}` },
      body: form,
    }, options.transcription.timeoutMs, input.signal);
    if (!response.ok) throw httpError(502, `文字起こしエンドポイントが HTTP ${response.status} を返しました。${await errorSnippet(response)}`);
    const payload = await response.json().catch(() => undefined);
    const text = payload !== null && typeof payload === 'object' && typeof payload.text === 'string' ? payload.text.trim() : '';
    return { text, provider: 'openai', engine: options.transcription.model, language, seconds: undefined };
  }

  if (!isRiffWave(input.audio)) {
    throw httpError(415, 'ローカル音声エンジンは 16kHz モノラルの WAV を受け取ります。マイクからは自動でこの形式になります。ファイルは WAV に変換するか、transcription.provider を openai にしてください。');
  }
  const registry = ctx.get?.('speechToText');
  if (registry === undefined) {
    throw httpError(503, '音声入力エンジンが組み込まれていません。voice-input バンドルを有効にするか、transcription.provider を openai にしてください。');
  }
  const ready = await ensureSpeechReady(registry, options, input.signal);
  let spec;
  try {
    spec = registry.resolve({ audio: input.audio, language });
  } catch (cause) {
    spec = registry.resolve({ audio: input.audio });
  }
  const transcript = await registry.transcribe(spec, input.signal);
  return {
    text: typeof transcript?.text === 'string' ? transcript.text.trim() : '',
    provider: 'harness',
    engine: ready.providerId,
    language: language ?? ready.language,
    seconds: typeof transcript?.audioSeconds === 'number' ? transcript.audioSeconds : undefined,
  };
}

/** Wait for the selected speech provider to finish its preparation. */
async function ensureSpeechReady(registry, options, signal) {
  const snapshot = registry.snapshot();
  const selection = snapshot.selection ?? {};
  const providers = Array.isArray(snapshot.providers) ? snapshot.providers : [];
  const provider = providers.find((entry) => entry.id === selection.providerId) ?? providers[0];
  if (provider === undefined) throw httpError(503, '利用できる音声認識プロバイダがありません。');
  const phase = provider.preparation?.phase;
  if (phase === 'ready' || phase === 'standby' || phase === 'waking') {
    return { providerId: provider.id, language: selection.language };
  }
  registry.prepare(provider.id);
  const deadline = Date.now() + options.transcription.prepareTimeoutMs;
  while (Date.now() < deadline) {
    await delay(700, signal);
    const current = registry.snapshot().providers.find((entry) => entry.id === provider.id);
    const currentPhase = current?.preparation?.phase;
    if (currentPhase === 'ready' || currentPhase === 'standby' || currentPhase === 'waking') {
      return { providerId: provider.id, language: selection.language };
    }
    if (currentPhase === 'failed') {
      throw httpError(503, `音声認識モデルの準備に失敗しました: ${current.preparation.message ?? '不明なエラー'}`);
    }
  }
  throw httpError(504, '音声認識モデルの準備がタイムアウトしました。');
}

