/**
 * Media Studio — Host half.
 *
 * Three capabilities over one dependency-free core:
 *
 *   - `generate_image`   image generation (free Pollinations by default, or any
 *                        OpenAI-compatible `/images/generations` endpoint);
 *   - `generate_speech`  speech synthesis (offline Windows SAPI by default, or
 *                        any OpenAI-compatible `/audio/speech` endpoint);
 *   - `transcribe_audio` voice input from an audio file, executed by the
 *                        mounted `speechToText` provider or an OpenAI-compatible
 *                        `/audio/transcriptions` endpoint.
 *
 * The same three paths back the authenticated same-origin routes the Web panel
 * uses (`/api/media-studio/*`), so the panel never needs a second provider
 * implementation and no credential ever reaches the browser.
 *
 * Generated bytes are stored through the attachment service when it is mounted
 * (the Chat renderer and the audio player then resolve them durably) and a copy
 * is written under the Session working directory for tool calls, so the model
 * can hand the user a real workspace path.
 */

