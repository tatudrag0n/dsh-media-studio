/** Read the mounted speech provider's readiness for the panel note. */
function harnessReadiness(ctx, options) {
  if (options.transcription.provider !== 'harness') return { ready: true, providerName: options.transcription.model, phase: 'ready' };
  const registry = ctx.get?.('speechToText');
  if (registry === undefined) return { ready: false, providerName: undefined, phase: 'unavailable' };
  try {
    const snapshot = registry.snapshot();
    const providers = Array.isArray(snapshot.providers) ? snapshot.providers : [];
    const selected = providers.find((entry) => entry.id === snapshot.selection?.providerId) ?? providers[0];
    if (selected === undefined) return { ready: false, providerName: undefined, phase: 'unavailable' };
    const phase = selected.preparation?.phase ?? 'unprepared';
    return {
      ready: phase === 'ready' || phase === 'standby' || phase === 'waking',
      providerName: selected.name,
      phase,
    };
  } catch {
    return { ready: false, providerName: undefined, phase: 'unknown' };
  }
}

