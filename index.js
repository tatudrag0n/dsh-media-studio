/** Keep a configured output directory relative and inside the Session cwd. */
export function safeRelativeDir(value) {
  const text = nonEmpty(value) ?? DEFAULT_OUTPUT_DIR;
  const normalized = text.replace(/[\\/]+/gu, '/').replace(/^\.\//u, '').replace(/\/+$/u, '');
  if (normalized === '' || normalized.startsWith('/') || /^[A-Za-z]:/u.test(normalized)
    || normalized.split('/').some((part) => part === '..')) {
    return DEFAULT_OUTPUT_DIR;
  }
  return normalized;
}

/** A finite positive number, or the fallback. */
function positive(value, fallback) {
  return typeof value === 'number' && Number.isFinite(value) && value > 0 ? value : fallback;
}

/** A trimmed non-empty string, or undefined. */
function nonEmpty(value) {
  return typeof value === 'string' && value.trim() !== '' ? value.trim() : undefined;
}

/** One of `allowed`, or the fallback. */
function pick(value, allowed, fallback) {
  return typeof value === 'string' && allowed.includes(value) ? value : fallback;
}

/** Strip a trailing slash from an endpoint base URL. */
function trimSlash(value) {
  return value.replace(/\/+$/u, '');
}

/** A short BCP 47-style language hint, or undefined. */
function normalizeLanguage(value) {
  const text = nonEmpty(value);
  return text !== undefined && /^[A-Za-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/u.test(text) ? text : undefined;
}

