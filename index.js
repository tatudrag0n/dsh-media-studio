/** The material library and the production pipeline for the panel. */
/**
 * Every tool a text command may run by name.
 *
 * `tools-list.js` is the single source of truth, so the panel route, the CLI,
 * `media_create`'s `tool` field and a text project file cannot drift apart.
 * `render_project` is added here but kept out of the catalogue: a project step
 * that named it would nest one project inside another.
 */
const PANEL_TOOL_NAMES = new Set([...STUDIO_TOOL_NAMES, 'render_project']);

/**
 * `POST /api/media-studio/tool`: run one studio tool by name.
 *
 * The body is `{ tool, args }`. Arguments are filtered against the tool's own
 * schema, so the route cannot smuggle anything the tool does not declare, and a
 * missing required argument comes back as a 400 that names it.
 *
 * This is the door the panel's studio tab uses. `media_create` routes a
 * sentence; the tools whose input is a timeline, a part list or an arrangement
 * cannot be derived from one, so they need a door that takes the name and the
 * structure.
 */
function toolRoutes(ctx) {
  return [{
    path: `${ROUTE_PREFIX}/tool`,
    methods: ['POST'],
    requestBody: 'buffered',
    fetch: respond(async (request) => {
      const body = await readJsonBody(request);
      const name = typeof body?.tool === 'string' ? body.tool.trim() : '';
      if (!PANEL_TOOL_NAMES.has(name)) {
        throw httpError(400, `このツールはパネルから実行できません: ${name === '' ? '(未指定)' : name}`);
      }
      const tool = ctx?.tools?.get?.(name) ?? ctx?.get?.('tools')?.get?.(name);
      if (tool === undefined || typeof tool.execute !== 'function') {
        throw httpError(503, `${name} が登録されていません。メディアスタジオのプラグインが有効か確認してください。`);
      }
      const properties = tool.parameters?.properties ?? {};
      const args = {};
      for (const [key, value] of Object.entries(body?.args ?? {})) {
        if (Object.hasOwn(properties, key)) args[key] = value;
      }
      const missing = (tool.parameters?.required ?? []).filter((key) => args[key] === undefined);
      if (missing.length > 0) throw httpError(400, `引数が足りません: ${missing.join(', ')}`);
      const exec = { signal: request.signal };
      const value = await tool.execute(args, exec);
      const blocks = tool.output?.render?.(args, value) ?? [];
      const text = blocks.filter((block) => block.type === 'text').map((block) => block.text).join('\n');
      const media = await readMedia(ctx, { resolveSessionCwd }, exec, value);
      return jsonResponse({ tool: name, text, value, ...(media == null ? {} : { media }) });
    }),
  }];
}

function productionRoutes(options) {
  return [
    {
      path: `${ROUTE_PREFIX}/assets`,
      methods: ['GET', 'POST'],
      requestBody: 'buffered',
      fetch: respond(async (request) => {
        const directory = assetDirectory(options);
        if (request.method === 'GET') {
          return jsonResponse({ assets: await listAssets(directory) });
        }
        const name = request.headers.get('x-file-name') ?? 'material';
        const data = new Uint8Array(await request.arrayBuffer());
        if (data.byteLength > options.assets.maxBytes) {
          throw httpError(413, `素材が大きすぎます (${Math.round(data.byteLength / 1024 / 1024)} MB)。`);
        }
        const record = await saveAsset(directory, { name, data });
        return jsonResponse({ asset: record });
      }),
    },
    {
      path: `${ROUTE_PREFIX}/asset-file`,
      methods: ['GET', 'HEAD'],
      requestBody: 'buffered',
      fetch: respond(async (request) => {
        const id = new URL(request.url).searchParams.get('id') ?? '';
        const found = await readAsset(assetDirectory(options), id);
        if (found === undefined) throw httpError(404, 'この素材が見つかりません。');
        if (request.method === 'HEAD') {
          return new Response(null, { status: 200, headers: { 'content-type': found.record.mediaType } });
        }
        return bytesResponse(found.data, found.record.mediaType);
      }),
    },
    {
      path: `${ROUTE_PREFIX}/asset-delete`,
      methods: ['POST'],
      requestBody: 'buffered',
      fetch: respond(async (request) => {
        const body = await readJsonBody(request);
        const removed = await removeAsset(assetDirectory(options), String(body.id ?? ''));
        return jsonResponse({ removed });
      }),
    },
    {
      path: `${ROUTE_PREFIX}/production`,
      methods: ['POST'],
      requestBody: 'buffered',
      fetch: respond(async (request) => {
        const body = await readJsonBody(request);
        const directory = assetDirectory(options);
        const library = await listAssets(directory);
        const byId = new Map(library.map((entry) => [entry.id, entry.path]));
        let spec;
        try {
          const scenes = (Array.isArray(body.scenes) ? body.scenes : []).map((scene) => {
            const chart = readChartInput(scene);
            return {
              type: scene?.type,
              template: scene?.template,
              text: scene?.text,
              subtitle: scene?.subtitle,
              duration: scene?.duration,
              transition: scene?.transition,
              materialId: scene?.materialId,
              backgroundImageId: scene?.backgroundImageId,
              logoId: scene?.logoId,
              background: scene?.background,
              foreground: scene?.foreground,
              accent: scene?.accent,
              ...(chart.labels === undefined && chart.series === undefined ? {} : { chart }),
            };
          });
          spec = parseProductionSpec({
            scenes,
            width: body.width ?? options.production.width,
            height: body.height ?? options.production.height,
            fps: body.fps ?? options.production.fps,
            format: body.format,
            style: body.style,
            seed: body.seed,
          });
        } catch (cause) {
          throw httpError(400, String(cause?.message ?? cause));
        }
        for (const scene of spec.scenes) {
          const ids = [scene.materialId, scene.backgroundImageId, scene.logoId].filter((value) => typeof value === 'string' && value !== '');
          for (const id of ids) {
            if (!byId.has(id)) throw httpError(400, `素材が見つかりません: ${id}`);
          }
        }
        let result;
        try {
          result = await runProductionRenderer(options, spec, { assets: Object.fromEntries(byId) });
        } catch (cause) {
          throw httpError(500, String(cause?.message ?? cause));
        }
        return bytesResponse(result.data, result.mediaType);
      }),
    },
  ];
}

