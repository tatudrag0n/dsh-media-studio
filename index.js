/** Timestamp component for generated file names. */
function timestamp() {
  return new Date().toISOString().replace(/[:.]/gu, '-').replace('T', '_').replace('Z', '');
}

/** Extension for a generated image media type. */
function imageExtension(mediaType) {
  if (mediaType === 'image/jpeg') return 'jpg';
  if (mediaType === 'image/webp') return 'webp';
  if (mediaType === 'image/gif') return 'gif';
  return 'png';
}

/** Extension for a media type the transcription endpoint receives. */
function extensionForMime(mediaType) {
  const normalized = mediaType.split(';')[0].trim().toLowerCase();
  if (normalized === 'audio/mpeg' || normalized === 'audio/mp3') return 'mp3';
  if (normalized === 'audio/webm') return 'webm';
  if (normalized === 'audio/ogg') return 'ogg';
  if (normalized === 'audio/mp4' || normalized === 'audio/m4a' || normalized === 'audio/x-m4a') return 'm4a';
  if (normalized === 'audio/flac') return 'flac';
  return 'wav';
}

/** Declared media type for a local audio path. */
function mediaTypeForPath(path) {
  const lower = path.toLowerCase();
  if (lower.endsWith('.mp3')) return 'audio/mpeg';
  if (lower.endsWith('.webm')) return 'audio/webm';
  if (lower.endsWith('.ogg') || lower.endsWith('.oga')) return 'audio/ogg';
  if (lower.endsWith('.m4a') || lower.endsWith('.mp4')) return 'audio/mp4';
  if (lower.endsWith('.flac')) return 'audio/flac';
  return 'audio/wav';
}

/** Require non-empty text within a ceiling, or fail with the field name. */
function requireText(value, limit, field) {
  const text = typeof value === 'string' ? value.trim() : '';
  if (text === '') throw httpError(400, `${field} は必須です。`);
  if (text.length > limit) throw httpError(400, `${field} が長すぎます（上限 ${limit} 文字）。`);
  return text;
}

/** A finite integer, or undefined. */
function numberOrUndefined(value) {
  return typeof value === 'number' && Number.isFinite(value) ? Math.trunc(value) : undefined;
}

/** Wait for a delay, cancellable by the caller. */
function delay(ms, signal) {
  return new Promise((resolvePromise, rejectPromise) => {
    if (signal?.aborted === true) {
      rejectPromise(signal.reason ?? new Error('aborted'));
      return;
    }
    const timer = setTimeout(() => {
      signal?.removeEventListener?.('abort', onAbort);
      resolvePromise();
    }, ms);
    const onAbort = () => {
      clearTimeout(timer);
      rejectPromise(signal.reason ?? new Error('aborted'));
    };
    signal?.addEventListener?.('abort', onAbort, { once: true });
  });
}

/** Human byte size for result text. */
export function formatBytes(bytes) {
  if (!Number.isFinite(bytes) || bytes < 0) return `${bytes} bytes`;
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

/** Shorten text for a title line. */
function truncate(text, limit) {
  const value = typeof text === 'string' ? text : '';
  return value.length <= limit ? value : `${value.slice(0, Math.max(0, limit - 1))}…`;
}

/** Extracted message from an unknown thrown value. */
function messageOf(value) {
  if (value instanceof Error) return value.message;
  if (typeof value === 'string') return value;
  try {
    return JSON.stringify(value);
  } catch {
    return String(value);
  }
}

