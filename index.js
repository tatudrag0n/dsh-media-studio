/** Resolve the Session working directory a tool call runs against. */
export async function resolveSessionCwd(ctx, exec) {
  const workingDirectory = ctx.get?.('workingDirectory');
  if (workingDirectory !== undefined && exec?.agent !== undefined) {
    try {
      return await workingDirectory.ensure(exec.agent, exec.signal);
    } catch {
      // Fall through to the default directory.
    }
  }
  if (workingDirectory !== undefined) {
    try {
      // A panel route has no Agent, so it carries the session id itself.
      const session = ctx.get?.('sessions')?.get?.(exec?.agent?.id ?? exec?.sessionId);
      if (session !== undefined) return workingDirectory.get(session);
    } catch {
      // Fall through to the process directory.
    }
  }
  return process.cwd();
}

/** Absolute path for a user-supplied audio path. */
function resolveInputPath(cwd, value) {
  const text = typeof value === 'string' ? value.trim() : '';
  if (text === '') throw new Error('path must be a non-empty string');
  return isAbsolute(text) ? resolve(text) : resolve(cwd, text);
}

/** Write a copy of generated bytes under the Session's media directory. */
async function saveWorkspaceCopy(ctx, exec, options, name, data) {
  try {
    const cwd = await resolveSessionCwd(ctx, exec);
    const directory = resolve(cwd, ...options.outputDir.split('/'));
    const relativeDirectory = directory.startsWith(cwd + sep) || directory === cwd ? directory : undefined;
    if (relativeDirectory === undefined) return undefined;
    await mkdir(relativeDirectory, { recursive: true });
    const target = join(relativeDirectory, name);
    await writeFile(target, data);
    return target;
  } catch {
    return undefined;
  }
}

